DROP TABLE IF EXISTS public.sostavscepok CASCADE;
DROP TABLE IF EXISTS public.scepki CASCADE;

-- 1. Главная таблица: scepki (Сцепки)
-- Первичный ключ: number_scepki (автоинкремент)
CREATE TABLE public.scepki (
    number_scepki INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kol_vagonov INT NOT NULL CHECK (kol_vagonov > 0),
    dlina_scepki REAL NOT NULL CHECK (dlina_scepki > 0),
    data_sostavleniya DATE NOT NULL,
    vozmozhnost_reversivnogo_dvizheniya BOOLEAN NOT NULL DEFAULT false
);

-- 2. Подчиненная таблица: sostavscepok (Составы сцепок)
-- Первичный ключ (PK): tramvai_number (номер трамвая)
-- Внешний ключ (FK): number_scepki -> scepki(number_scepki)
CREATE TABLE public.sostavscepok (
    tramvai_number INT PRIMARY KEY,
    number_scepki INT NOT NULL,
    main_tramvai BOOLEAN NOT NULL DEFAULT false,
    vagon_number_in_scepka INT NOT NULL CHECK (vagon_number_in_scepka > 0),
    CONSTRAINT fk_sostavscepok_scepki FOREIGN KEY (number_scepki)
        REFERENCES public.scepki (number_scepki)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

